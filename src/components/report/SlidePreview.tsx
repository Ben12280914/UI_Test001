import type { ReactNode } from "react";
import { ValidationDot } from "@/components/ui/Badges";
import { ACTIVITY_STATUS_LABELS, AUDIENCE_LABELS } from "@/domain/constants";
import type { Report, ReportSection, SectionKey } from "@/domain/types";
import { cx } from "@/lib/format";

/**
 * PPT-like preview of the report. Each section is rendered as a 16:9 slide so the structure
 * maps 1:1 onto a corporate PPT template engine later.
 */
function Slide({ no, title, children, total }: { no: number; title: string; children: ReactNode; total: number }) {
  return (
    <div className="slide card relative aspect-[16/9] overflow-hidden bg-white">
      <div className="absolute inset-x-0 top-0 h-1.5 bg-brand-500" />
      <div className="flex h-full flex-col px-10 pb-6 pt-8">
        <div className="mb-5 flex items-end justify-between border-b-2 border-navy-800 pb-2">
          <h2 className="text-xl font-bold text-navy-900">{title}</h2>
          <span className="text-[11px] font-semibold text-slate-400">TKG · 이지</span>
        </div>
        <div className="min-h-0 flex-1 overflow-hidden">{children}</div>
        <div className="mt-3 flex items-center justify-between text-[10px] text-slate-400">
          <span>Source-traceable report · generated by 이지 AI Reporting Agent</span>
          <span>
            {no} / {total}
          </span>
        </div>
      </div>
    </div>
  );
}

function Bullets({ section, empty = "해당 기간 내용 없음" }: { section?: ReportSection; empty?: string }) {
  if (!section || section.items.length === 0) return <div className="text-sm text-slate-400">{empty}</div>;
  return (
    <ul className="space-y-2.5">
      {section.items.map((i) => (
        <li key={i.id} className="flex gap-2.5 text-[15px] leading-snug text-slate-800">
          <ValidationDot status={i.validation.status} />
          <span>{i.text}</span>
        </li>
      ))}
    </ul>
  );
}

export function SlidePreview({ report }: { report: Report }) {
  const sec = (k: SectionKey) => report.sections.find((s) => s.key === k);
  const version = report.versions.at(-1);
  const progress = sec("project_progress");
  const slides: { title: string; body: ReactNode }[] = [
    { title: "Executive Summary", body: <Bullets section={sec("executive_summary")} /> },
    { title: "Key Achievements", body: <Bullets section={sec("key_achievements")} /> },
    {
      title: "Project Status",
      body: (
        <div className="grid h-full grid-cols-[1fr_1.4fr] gap-6">
          <table className="w-full self-start text-sm">
            <thead>
              <tr className="border-b border-slate-200 text-left text-[11px] uppercase tracking-wide text-slate-500">
                <th className="py-1.5">Project</th>
                <th className="py-1.5">Status</th>
                <th className="py-1.5 text-right">Last</th>
              </tr>
            </thead>
            <tbody>
              {report.projectSnapshots.map((p) => (
                <tr key={p.projectName} className="border-b border-slate-100">
                  <td className="py-1.5 font-medium text-navy-900">{p.projectName}</td>
                  <td className={cx("py-1.5 text-xs font-semibold", p.status === "delayed" ? "text-brand-600" : p.status === "completed" ? "text-emerald-600" : "text-sky-700")}>
                    {ACTIVITY_STATUS_LABELS[p.status]}
                    {p.hasRisk && p.status !== "delayed" ? " · Risk" : ""}
                  </td>
                  <td className="py-1.5 text-right text-xs tabular-nums text-slate-500">{p.lastActivityDate.slice(5)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="text-[13px]">
            <Bullets section={progress} />
          </div>
        </div>
      ),
    },
    { title: "KPI / Quantitative Impact", body: <Bullets section={sec("kpi")} empty="Source에 기록된 정량 지표가 없습니다." /> },
    { title: "Issues & Risks", body: <Bullets section={sec("issues_risks")} /> },
    { title: "Next Actions", body: <Bullets section={sec("next_actions")} /> },
  ];
  const total = slides.length + 1;

  return (
    <div className="mx-auto max-w-5xl space-y-6">
      <div className="slide card relative aspect-[16/9] overflow-hidden bg-navy-900 text-white">
        <div className="absolute inset-y-0 left-0 w-2 bg-brand-500" />
        <div className="flex h-full flex-col justify-between px-14 py-12">
          <div className="text-sm font-semibold tracking-widest text-brand-200">TKG · OPEX / DX</div>
          <div>
            <div className="text-4xl font-bold leading-tight">{report.title}</div>
            <div className="mt-3 text-lg text-navy-200">
              {report.periodStart} ~ {report.periodEnd}
            </div>
          </div>
          <div className="flex items-end justify-between text-sm text-navy-200">
            <div>
              {report.department} · {report.author}
              <br />
              Audience: {AUDIENCE_LABELS[report.audience]}
            </div>
            <div className="text-right">
              v{version?.version} {version?.label}
              <br />
              {report.status === "ARCHIVED" ? "FINAL" : report.status.replace(/_/g, " ")}
            </div>
          </div>
        </div>
      </div>
      {slides.map((s, i) => (
        <Slide key={s.title} no={i + 2} total={total} title={s.title}>
          {s.body}
        </Slide>
      ))}
    </div>
  );
}
